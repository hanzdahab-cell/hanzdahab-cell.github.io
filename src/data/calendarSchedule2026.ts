function computeStatus(startIso: string, endIso: string): 'past' | 'current' | 'upcoming' {
  const simNow = '2026-09-21';
  if (endIso < simNow) return 'past';
  if (startIso <= simNow && endIso >= simNow) return 'current';
  return 'upcoming';
}

